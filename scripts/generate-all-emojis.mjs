/**
 * Generates modules/all-emojis.js from scripts/emoji-test.txt (fully-qualified sequences).
 * Run: node scripts/generate-all-emojis.mjs
 */
import { readFileSync, writeFileSync } from 'fs';
import { dirname, join } from 'path';
import { fileURLToPath } from 'url';

const __dirname = dirname(fileURLToPath(import.meta.url));
const EMOJI_TEST_PATH = join(__dirname, 'emoji-test.txt');
const OUT_PATH = join(__dirname, '..', 'modules', 'all-emojis.js');

function parseEmojiTest(text) {
    const seen = new Set();
    const list = [];

    for (const line of text.split('\n')) {
        if (!line || line.startsWith('#')) {
            continue;
        }
        const semi = line.indexOf(';');
        if (semi === -1) {
            continue;
        }
        const meta = line.slice(semi + 1);
        if (!/fully-qualified/i.test(meta)) {
            continue;
        }
        const hash = meta.indexOf('#');
        if (hash === -1) {
            continue;
        }
        const afterHash = meta.slice(hash + 1).trim();
        const emoji = afterHash.split(/\s+/)[0];
        if (!emoji || seen.has(emoji)) {
            continue;
        }
        seen.add(emoji);
        list.push(emoji);
    }

    return list;
}

function main() {
    const text = readFileSync(EMOJI_TEST_PATH, 'utf8');
    const emojis = parseEmojiTest(text);

    const output = `/* eslint-disable */
/* AUTO-GENERATED by scripts/generate-all-emojis.mjs — do not edit manually */
/* Unicode emoji-test.txt (fully-qualified), ${emojis.length} sequences */
(function (global) {
    'use strict';
    const ALL_UTF8_EMOJIS = ${JSON.stringify(emojis)};
    global.VKTeamsAllEmojis = {
        list: ALL_UTF8_EMOJIS,
        count: ALL_UTF8_EMOJIS.length
    };
})(typeof globalThis !== 'undefined' ? globalThis : window);
`;

    writeFileSync(OUT_PATH, output, 'utf8');
    console.log(`Parsed ${emojis.length} emojis from ${EMOJI_TEST_PATH}`);
    console.log(`Wrote ${OUT_PATH}`);
}

main();
